"""
反思教训（Lesson）相关 prompt 模板

三类 prompt：
- LESSON_DISTILL_PROMPT:  在线自评失败 → 提炼成可复用的教训（落点3）
- LESSON_FROM_CASE_PROMPT: 单条评测失败样本 → 抽象出系统级教训（落点4 兜底）
- LESSON_ATTRIBUTION_PROMPT: 批量评测失败样本 → 归纳系统层面改进教训（落点4 主路径）

占位符统一用 str.format 风格。
"""

# ── 落点 3：在线自评失败 → 教训 ──────────────────────────────
LESSON_DISTILL_PROMPT = """分析以下一次失败的回答，提炼出一条可复用的教训。

## 失败信息
- 用户问题：{question}
- 检索到的资料：{context}
- 实际回答：{answer}
- 自评失败原因：{fail_reason}

## 提炼要求
1. 抽象出**问题类型**层面的规律，不要绑定具体数值、具体文档、具体设备编号
2. 必须是一条**可独立理解的陈述句**，能脱离本次对话被单独理解
3. 描述的是"这类问题应该怎么做"，不是"这次做错了什么"
4. 一句话，不超过 60 字

## 正例
错误示范：case-042 问检修周期，答案漏了"每年一次"
正确示范：问设备检修/检维修周期时，答案必须给出具体周期数值，不能只说"按需安排"

错误示范：这次没引用第3页的数据
正确示范：涉及具体参数数值时，必须标注对应的来源章节和页码

## 输出格式
只返回一条教训文本，不要 JSON，不要解释。
如果这次失败不具有可泛化的规律，返回空字符串。"""


# ── 落点 4：单条评测失败样本 → 系统级教训 ──────────────────
LESSON_FROM_CASE_PROMPT = """根据以下评测失败样本，抽象出一条可复用的系统级教训。

## 失败样本
- 问题：{question}
- 期望答案要点：{reference}
- 实际回答：{answer}
- 各项得分：{scores}
- 失败原因：{fail_reasons}

## 提炼要求
1. 抽象出同类问题的通用规律，不绑定本 case 的具体内容
2. 指向一个明确的改进动作（改检索策略 / 改 prompt 约束 / 改查询改写逻辑 / 改分块策略）
3. 一句话，不超过 60 字

只返回教训文本，不要解释。无法抽象就返回空字符串。"""


# ── 落点 4：批量评测失败样本 → 系统级教训（能发现模式）────
LESSON_ATTRIBUTION_PROMPT = """分析以下一批评测失败样本，归纳出系统层面的改进教训。

## 失败样本
{cases}

## 归因要求
1. 先按失败维度归类（召回不足 / 忠实度不足 / 答案不完整 / 引用不对齐 / 问题理解偏差）
2. 每条教训必须指向**一个明确的改进动作**（改检索策略 / 改 prompt 约束 / 改查询改写逻辑 / 改分块策略）
3. 描述系统行为层面的规律，不绑定单个 case
4. 相同维度的失败合并成一条，不要逐 case 输出
5. 每条不超过 60 字

## 输出格式
严格返回 JSON 数组，不要其他文字：
[{{"dimension": "召回|忠实|完整|引用|理解", "action": "改进动作", "lesson": "教训文本", "confidence": 0.0-1.0}}]

没有可归纳的规律就返回空数组 []"""
